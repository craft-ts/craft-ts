#!/usr/bin/env node
/**
 * Generates the `.pipe(...)` overloads of `CraftStream` (arities 1..MAX) into
 * `libs/stream/src/lib/craft-stream-pipe.generated.ts`.
 *
 * Explicit overloads, not a recursive variadic type: every operator slot is
 * inferred flat from its predecessor, which keeps inference cheap and errors
 * readable. Past MAX operators, nest `.pipe(...).pipe(...)` — the rest overload
 * deliberately collapses to `CraftStream<unknown, unknown>` rather than
 * pretending to type an unbounded chain.
 *
 * Usage: node tools/generate-stream-pipe.mjs [--check]
 *        --check fails (exit 1) when the committed file is out of date.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const MAX = 14;
const here = dirname(fileURLToPath(import.meta.url));
const target = resolve(
  here,
  '../libs/stream/src/lib/craft-stream-pipe.generated.ts',
);

function overload(arity) {
  const generics = Array.from(
    { length: arity },
    (_, index) => `A${index + 1}, Y${index + 1}`,
  ).join(', ');
  const parameters = Array.from({ length: arity }, (_, index) => {
    const from = index === 0 ? 'A, Y' : `A${index}, Y${index}`;
    return `    op${index + 1}: StreamOperator<${from}, A${index + 1}, Y${index + 1}>,`;
  }).join('\n');
  return `  <${generics}>(\n${parameters}\n  ): CraftStream<A${arity}, Y${arity}>;`;
}

const overloads = Array.from({ length: MAX }, (_, index) =>
  overload(index + 1),
).join('\n');

const output = `// <auto-generated by tools/generate-stream-pipe.mjs — do not edit by hand>
import type { CraftStream, StreamOperator } from './craft-stream';

/**
 * The \`.pipe(...)\` method of a {@link CraftStream}: applies operators
 * left-to-right, each slot inferred from the previous one (arities 1..${MAX}).
 * Beyond ${MAX} operators, nest \`.pipe(...).pipe(...)\`.
 */
export interface CraftStreamPipe<A, Y> {
${overloads}
  (
    ...operators: ReadonlyArray<StreamOperator<any, any, any, any>>
  ): CraftStream<unknown, unknown>;
}
`;

if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8');
  if (current !== output) {
    process.stderr.write(
      `${target} is out of date; run node tools/generate-stream-pipe.mjs\n`,
    );
    process.exit(1);
  }
} else {
  writeFileSync(target, output);
  process.stdout.write(`wrote ${join('libs/stream/src/lib', 'craft-stream-pipe.generated.ts')}\n`);
}
