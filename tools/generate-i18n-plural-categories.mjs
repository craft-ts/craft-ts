// Keep compile-time cardinal categories aligned with Unicode CLDR.
// Runtime validation deliberately uses the host's Intl.PluralRules data.
import { writeFile } from 'node:fs/promises';
import { format } from 'prettier';
const version = '48.0.0';
const source = `https://raw.githubusercontent.com/unicode-org/cldr-json/${version}/cldr-json/cldr-core/supplemental/plurals.json`;
const response = await fetch(source);
if (!response.ok) throw new Error(`CLDR download failed: ${response.status}`);
const data = await response.json();
const rules = data.supplemental['plurals-type-cardinal'];
const entries = Object.entries(rules).sort(([a], [b]) => a.localeCompare(b));
const lines = entries.map(([locale, categories]) => {
  const names = Object.keys(categories).map((key) =>
    key.replace('pluralRule-count-', ''),
  );
  return `  '${locale.toLowerCase()}': [${names.map((name) => `'${name}'`).join(', ')}],`;
});
await writeFile(
  new URL('../libs/i18n/src/lib/plural-categories.ts', import.meta.url),
  await format(
    `// Generated by tools/generate-i18n-plural-categories.mjs from Unicode CLDR ${version}.\n// Source: ${source}\nexport const pluralCategoriesByLocale = {\n${lines.join('\n')}\n} as const;\n`,
    { parser: 'typescript', singleQuote: true },
  ),
);
